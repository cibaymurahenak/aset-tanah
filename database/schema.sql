CREATE TABLE IF NOT EXISTS lahan (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  pulau VARCHAR(50) NOT NULL,
  lokasi VARCHAR(150) NOT NULL,
  luas_m2 DECIMAL(14,2) NOT NULL DEFAULT 0,
  ha DECIMAL(12,4) NOT NULL DEFAULT 0,
  znt BIGINT UNSIGNED NOT NULL DEFAULT 0,
  nilai BIGINT UNSIGNED NOT NULL DEFAULT 0,
  konteks TEXT,
  produk VARCHAR(100) NOT NULL,
  alt VARCHAR(100),
  alasan TEXT,
  kapasitas TEXT,
  prov VARCHAR(80) NOT NULL,
  foto VARCHAR(255) NULL,
  foto_batas VARCHAR(255) NULL,
  foto_akses VARCHAR(255) NULL,
  foto_sekitar VARCHAR(255) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS location (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  lahan_id INT UNSIGNED NOT NULL UNIQUE,
  provinsi VARCHAR(100) NOT NULL,
  kota VARCHAR(150) NOT NULL,
  alamat TEXT NULL,
  maps_link VARCHAR(500) NULL,
  kota_populasi_juta DECIMAL(10,3) NULL,
  kota_umk BIGINT UNSIGNED NULL,
  kota_vp TINYINT(1) NOT NULL DEFAULT 0,
  kota_vu TINYINT(1) NOT NULL DEFAULT 0,
  kota_catatan TEXT NULL,
  prov_populasi_juta DECIMAL(10,3) NULL,
  prov_v TINYINT(1) NOT NULL DEFAULT 0,
  prov_tier TINYINT UNSIGNED NOT NULL DEFAULT 0,
  prov_development TEXT NULL,
  prov_development_level TINYINT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_location_lahan FOREIGN KEY (lahan_id) REFERENCES lahan(id) ON DELETE CASCADE,
  INDEX idx_location_provinsi (provinsi),
  INDEX idx_location_kota (kota)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS lahan_poi (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  lahan_id INT UNSIGNED NOT NULL,
  nama VARCHAR(200) NOT NULL,
  kategori VARCHAR(100) NOT NULL,
  deskripsi TEXT NULL,
  cakupan VARCHAR(100) NULL,
  jarak_km DECIMAL(8,2) NULL,
  waktu_menit SMALLINT UNSIGNED NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_lahan_poi_lahan FOREIGN KEY (lahan_id) REFERENCES lahan(id) ON DELETE CASCADE,
  INDEX idx_lahan_poi_lahan (lahan_id),
  INDEX idx_lahan_poi_kategori (kategori)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
